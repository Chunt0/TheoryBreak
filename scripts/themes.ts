// Builds src/client/themes.css from the design kit's themes (putty-ai-design/): the same
// tokens, plus color-scheme, a legible on-accent and an accent fill for every theme. Run: bun scripts/themes.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { THEMES } from '../putty-ai-design/themes.ts';

const css = readFileSync('putty-ai-design/themes.css', 'utf8');
const blocks = new Map<string, [string, string][]>();
for (const m of css.matchAll(/\[data-theme="([^"]+)"\]\{[^\n]*\n([\s\S]*?)\n\}/g)) {
  const props: [string, string][] = [];
  for (const line of m[2].split('\n')) {
    const p = /^\s*(--[\w-]+):\s*([^;]+);/.exec(line);
    if (p && !line.includes('@kind')) props.push([p[1], p[2].trim()]);
  }
  blocks.set(m[1], props);
}

const hex = (h: string) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16) / 255);
const lum = (h: string) => {
  const [r, g, b] = hex(h).map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const contrast = (a: string, b: string) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};

// tokens the app reads; the chat-only ones (bubbles, mascot) stay out
const SKIP = new Set(['--user-bubble', '--brand-putty', '--red', '--ease-brand']);
let out = `/* Themes, from the design kit (putty-ai-design/themes.css). Each theme is five base
   colours (bg, fg, panel, border, accent) with the rest derived. Set data-theme on <html>;
   with none, the default Mono theme follows the system's light or dark (see styles.css).
   Added here: color-scheme (so tone and status colours pick their light or dark set), an
   on-accent that stays legible on the accent, and an --accent-solid (the fill behind text) for every theme.
   Generated by scripts/themes.ts (bun scripts/themes.ts); edit the kit, not this file. */
`;
for (const t of Object.values(THEMES)) {
  const props = blocks.get(t.key);
  if (!props) throw new Error(`no block for ${t.key}`);
  const get = (k: string) => props.find(([p]) => p === k)?.[1];
  const fill = get('--accent-solid') ?? t.colors.accent;
  const inks = ['#ffffff', get('--bg')!, get('--heading')!, '#111111'];
  const ink = inks.reduce((a, b) => (contrast(b, fill) > contrast(a, fill) + 0.01 ? b : a));
  const lines = [`color-scheme: ${t.light ? 'light' : 'dark'};`];
  for (const [p, v] of props) if (!SKIP.has(p) && p !== '--on-accent') lines.push(`${p}: ${v};`);
  lines.push(`--on-accent: ${ink};`);
  if (!get('--accent-solid')) lines.push(`--accent-solid: ${t.colors.accent};`, `--accent-solid-hover: ${get('--accent2')};`, `--accent-solid-press: ${t.colors.accent};`);
  console.log(t.key.padEnd(12), 'fill', fill, 'ink', ink, contrast(ink, fill).toFixed(2), 'accent/bg', contrast(t.colors.accent, t.colors.bg).toFixed(2));
  out += `:root[data-theme="${t.key}"] {\n  ${lines.join('\n  ')}\n}\n`;
}
writeFileSync('src/client/themes.css', out);
